package report

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/joegarbett/rua-tool/internal/scan"
)

// Draft is a reviewable disclosure notice. The tool never sends mail — a human
// reviews and sends the draft.
type Draft struct {
	Subject    string
	Body       string
	Recipients []string
	Filename   string
}

// Build produces a disclosure draft for a finding. fromName is an optional
// sign-off.
func Build(f scan.Finding, c Contact, fromName string) Draft {
	scanned := f.ScannedDomain
	reportDomain := f.ReportDomain
	addresses := strings.Join(f.Addresses, ", ")

	subject := fmt.Sprintf("Security: DMARC reports for %s sent to an unregistered domain (%s)", scanned, reportDomain)
	if f.Severity() == scan.SeverityMedium {
		subject = fmt.Sprintf("Security: DMARC report domain for %s is expiring (%s)", scanned, reportDomain)
	}

	signoff := "\n\nRegards,\nA security researcher"
	if fromName != "" {
		signoff = "\n\nRegards,\n" + fromName
	}

	var riskLine string
	if f.Status.IsVulnerable() {
		riskLine = fmt.Sprintf("The domain **%s** appears to be UNREGISTERED and available to anyone. "+
			"Because your DMARC record directs aggregate/forensic reports there, an attacker who registers "+
			"it would begin receiving DMARC reports about mail using %s — leaking your sending sources, "+
			"volumes, and authentication failures, and aiding targeted spoofing.", reportDomain, scanned)
	} else {
		expiry := ""
		if f.Status.ExpiresAt != "" {
			expiry = " (expiry: " + f.Status.ExpiresAt + ")"
		}
		riskLine = fmt.Sprintf("The domain **%s** that receives your DMARC reports is expiring soon%s. "+
			"If it lapses, an attacker could register it and receive your DMARC reports.", reportDomain, expiry)
	}

	body := fmt.Sprintf(`Hello,

I'm reaching out about a DMARC configuration issue affecting %s.

Your DMARC record ( _dmarc.%s ) sends reports to address(es) at another domain:

  Report addresses : %s
  Report domain    : %s
  Status           : %s (checked via %s, %s confidence)

Risk
%s

Your published DMARC record
  %s

Suggested remediation
  - Register/renew %s, or
  - Update your DMARC rua=/ruf= addresses to a domain you control, then confirm
    the DMARC report-authorization record if reporting cross-domain
    (see RFC 7489 section 7.1).

This report was generated by automated DMARC-hygiene tooling and verified before
sending. Please treat it as a good-faith, responsible-disclosure notice. I hold no
data of yours and am not requesting anything in return.%s`,
		scanned,
		scanned,
		addresses,
		reportDomain,
		f.Status.State, f.Status.Method, f.Status.Confidence,
		riskLine,
		f.DMARCRaw,
		reportDomain,
		signoff,
	)

	return Draft{
		Subject:    subject,
		Body:       body,
		Recipients: c.Contacts,
		Filename:   "report-" + sanitiseFilename(scanned) + ".txt",
	}
}

var unsafeFilename = regexp.MustCompile(`[^a-zA-Z0-9.\-]`)

func sanitiseFilename(s string) string { return unsafeFilename.ReplaceAllString(s, "_") }
